#!/usr/bin/env node
//
// Regenerates the address registry the relay's jurisdiction check reads.
//
// Downloads the national address registry (Staðfangaskrá) from the public HMS
// export via iceaddr-ts's streaming parser and writes data/addresses.seed.sql —
// a D1-executable snapshot of the rows the relay needs (SVFNR, street, house,
// postcode, WGS84 coordinate).
//
//   node scripts/refresh-registry.mjs
//   wrangler d1 execute borgarland-relay --file data/addresses.seed.sql
//
// The FULL registry is written, not a Reykjavík subset. The relay must be able
// to reverse-look a Kópavogur point to a Kópavogur address, or the jurisdiction
// check would wrongly pass it; see src/registry.ts. (The small Reykjavík subset
// that "ships on the phone" is the app's concern, not the relay's.)
//
// HMS is the national housing authority, not a city host: this script touches
// no Reykjavík endpoint and never files anything. The city's form stays
// untouched — see AGENTS.md and decisions/0006.
//
// The registry is a cache with a date, not truth. Refresh on a schedule
// (upstream updates at least daily) and re-apply the seed, then let new
// isolates pick the rows up (src/registry-loader.ts).
//
// The snapshot is attributed to its source:
//   Staðfangaskrá by HMS / Þjóðskrá Íslands, CC-BY 4.0.

import { createWriteStream } from 'node:fs'
import { once } from 'node:events'
import { streamStadfangaskra } from 'iceaddr-ts'

const BATCH = 500

const out = createWriteStream(new URL('../data/addresses.seed.sql', import.meta.url))
let count = 0
let batch = []

function esc(value) {
  return value.replace(/'/g, "''")
}

function tuple(row) {
  if (row.lat === null || row.lng === null) return null
  const svfnr = row.svfnr === null ? 'NULL' : String(row.svfnr)
  const houseNumber = row.houseNumber === null ? 'NULL' : String(row.houseNumber)
  const houseLetter = row.houseLetter === null ? 'NULL' : `'${esc(row.houseLetter)}'`
  return `(${svfnr}, '${esc(row.streetNf)}', ${houseNumber}, ${houseLetter}, '${esc(row.postalCode)}', ${row.lat}, ${row.lng})`
}

function flush() {
  if (batch.length === 0) return
  out.write(
    `INSERT INTO addresses (svfnr, street_nf, house_number, house_letter, postal_code, lat, lng) VALUES\n${batch.join(',\n')};\n`,
  )
  count += batch.length
  batch = []
}

out.write('-- Generated by scripts/refresh-registry.mjs — do not edit.\n')
out.write('-- Snapshot of Staðfangaskrá (HMS / Þjóðskrá Íslands, CC-BY 4.0), taken ')
out.write(`${new Date().toISOString()}.\n`)
out.write('-- Apply with: wrangler d1 execute borgarland-relay --file data/addresses.seed.sql\n')

for await (const row of streamStadfangaskra()) {
  const t = tuple(row)
  if (t === null) continue
  batch.push(t)
  if (batch.length >= BATCH) flush()
}
flush()

out.end('\n')
await once(out, 'finish')
console.log(`wrote ${count} address rows to data/addresses.seed.sql`)
